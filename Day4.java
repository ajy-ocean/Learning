public class Day4 {
    public static void main(String[] args) {
        int score = 10;

        System.out.println(score);

        score = 20;
        System.out.println(score);

        score += 5;
        System.out.println(score);

        score -= 3;
        System.out.println(score);

        System.out.println(score++);
        System.out.println(score);

        System.out.println(++score);
        System.out.println(score);
    }
}
